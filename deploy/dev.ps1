function Invoke-Up {
    Assert-Tools
    foreach ($d in @($stateDir, $logDir)) { if (-not (Test-Path $d)) { New-Item -ItemType Directory -Path $d | Out-Null } }
    $running = @(Get-Processes | Where-Object { Test-Alive $_.pid })
    if ($running.Count -gt 0) {
        Write-Host "Already running ($(($running | ForEach-Object { $_.name }) -join ', ')). Use '.\deploy\dev.ps1 status' or 'down' first." -ForegroundColor Yellow
        return
    }

    $busy = @(Get-BusyPorts @(3100, 5600, 5603))
    if ($busy.Count -gt 0) {
        throw "Port(s) $($busy -join ', ') already in use by something dev.ps1 didn't start (an API or 'next dev' from another terminal?). Stop it first; dev.ps1 won't kill processes it doesn't own."
    }

    Initialize-EnvFiles

    Write-Step 'Dependencies'
    if (-not (Test-Path (Join-Path $api 'node_modules'))) { Invoke-Yarn $api @('install') 'api: yarn install'; Write-Host '  installed api' }
    else { Write-Host '  api ok' }
    if (-not (Test-Path (Join-Path $fe 'node_modules'))) { Invoke-Yarn $fe @('install') 'frontend: yarn install'; Write-Host '  installed frontend' }
    else { Write-Host '  frontend ok' }

    Write-Step 'Dev containers (portfolio-*)'
    Invoke-Quiet $api 'docker' (@('compose', '-f', $composeFile, 'up', '-d', '--wait') + $services) 'docker compose up' | Out-Null
    Write-Host "  up       $($services -join ', ')"

    Write-Step 'Database: migrations + seed (idempotent)'
    Invoke-Yarn $api @('prisma:dev:deploy') 'prisma migrate deploy'
    Write-Host '  migrated'
    Invoke-Yarn $api @('prisma:dev:seed') 'seed'
    Write-Host '  seeded'

    Write-Step 'Local device gate (https://localhost:8443)'
    Invoke-Quiet $repo 'powershell' @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $gate, 'up', '-Target', 'local') 'gate up' | Out-Null
    Write-Host '  up'

    Write-Step 'API + Next apps'
    $procs = @()
    $procs += Start-Background 'api' $api @($yarn, 'dotenv', '-e', '.env.dev', '--', 'nest', 'start', '--watch')
    $procs += Start-Background 'next' $fe @($yarn, 'dev')
    ConvertTo-Json -InputObject @($procs) | Set-Content -Path $pidFile -Encoding UTF8
    Wait-Http 'api' 'http://localhost:3100/v1/health' @(200) 120 (Join-Path $logDir 'api.log')
    Wait-Http 'web' 'http://localhost:5600/en' @(200) 180 (Join-Path $logDir 'next.log')
    Wait-Http 'admin' 'http://localhost:5603/login' @(200) 180 (Join-Path $logDir 'next.log')
    Wait-Http 'gate' 'https://localhost:8443/' @(404, 200, 307) 30 ''

    $listing = Invoke-Quiet $repo 'powershell' @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $gate, 'list', '-Target', 'local') 'gate list'
    $hasDevice = @($listing | Where-Object { $_ -match '\bOK\s*$' }).Count -gt 0
    if (-not $hasDevice) {
        if ($NoBrowser) {
            Write-Host "`nNo browser is enrolled in the local gate yet. Run:" -ForegroundColor Yellow
            Write-Host "  .\deploy\device-gate\gate.ps1 enroll -Device $Device -Target local"
        } else {
            Write-Step "Enrolling this browser as '$Device' (a one-time link opens in your default browser)"
            & powershell -NoProfile -ExecutionPolicy Bypass -File $gate enroll -Device $Device -Target local -TimeoutSec 180
        }
    }

    Write-Host ''
    Write-Host 'Local stack is up:' -ForegroundColor Green
    Write-Host '  web      http://localhost:5600'
    Write-Host '  admin    https://localhost:8443   (through the device gate; accept the self-signed cert once)'
    Write-Host '  api      http://localhost:3100/v1'
    Write-Host '  mail     http://localhost:8026    (Mailpit)'
    Write-Host '  rabbitmq http://localhost:15673   (portfolio / portfolio)'
    Write-Host "  logs     $logDir"
    if ($script:createdApiEnv) {
        Write-Host ''
        Write-Host 'First run: sign in with SEED_ADMIN_EMAIL / SEED_ADMIN_PASSWORD from api/.env.dev, then set up TOTP.' -ForegroundColor Yellow
    }
}

function Invoke-Down {
    Write-Step 'Stopping API + Next apps'
    foreach ($p in Get-Processes) {
        if (Test-Alive $p.pid) { Stop-Tree $p.pid; Write-Host "  stopped  $($p.name) (pid $($p.pid))" }
    }
    if (Test-Path $pidFile) { Remove-Item $pidFile -Force }
    Write-Step 'Stopping the local gate and dev containers (data kept)'
    Invoke-Quiet $repo 'powershell' @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $gate, 'down', '-Target', 'local') 'gate down' | Out-Null
    Invoke-Quiet $api 'docker' @('compose', '-f', $composeFile, 'stop') 'docker compose stop' | Out-Null
    Write-Host '  stopped'
}

function Invoke-Status {
    Write-Host 'Containers:'
    $prev = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    $rows = & docker ps -a --filter 'name=portfolio-' --format '{{.Names}}|{{.Status}}|{{.Ports}}' 2>$null
    $ErrorActionPreference = $prev
    if (-not $rows) { Write-Host '  (none)' }
    foreach ($r in @($rows)) {
        $c = "$r".Split('|')
        $ports = ($c[2] -replace '127\.0\.0\.1:', '' -replace '->\d+/tcp', '' -replace ', \[::\]:\d+', '')
        Write-Host ('  {0,-26} {1,-28} {2}' -f $c[0], $c[1], $ports)
    }
    Write-Host 'Processes:'
    $procs = @(Get-Processes)
    if ($procs.Count -eq 0) { Write-Host '  (none started by dev.ps1)' }
    foreach ($p in $procs) {
        $state = 'stopped'
        if (Test-Alive $p.pid) { $state = 'running' }
        Write-Host ('  {0,-6} pid {1,-7} {2}' -f $p.name, $p.pid, $state)
    }
    Write-Host 'Endpoints:'
    $checks = [ordered]@{
        'api   http://localhost:3100/v1/health' = 'http://localhost:3100/v1/health'
        'web   http://localhost:5600/en'        = 'http://localhost:5600/en'
        'admin http://localhost:5603/login'     = 'http://localhost:5603/login'
        'gate  https://localhost:8443/'         = 'https://localhost:8443/'
        'mail  http://localhost:8026/'          = 'http://localhost:8026/'
    }
    foreach ($k in $checks.Keys) {
        $code = Get-HttpStatus $checks[$k]
        $label = "$code"
        if ($code -eq 0) { $label = 'down' }
        if ($k -like 'gate*' -and $code -eq 404) { $label = '404 (up; gate blocks unenrolled requests)' }
        Write-Host ('  {0,-40} {1}' -f $k, $label)
    }
}

function Invoke-Reset {
    Write-Host 'This wipes ALL local dev data: the portfolio dev database (incl. your local admin user and TOTP),'
    Write-Host 'Redis, RabbitMQ, local S3 media and dev.ps1 logs. Env files and enrolled gate devices are kept.'
    if (-not $Yes) {
        $answer = Read-Host "Type 'reset' to continue"
        if ($answer -ne 'reset') { Write-Host 'Cancelled. Nothing was changed.'; return }
    }
    Invoke-Down
    Write-Step 'Removing dev containers and their volumes'
    Invoke-Quiet $api 'docker' @('compose', '-f', $composeFile, 'down', '-v') 'docker compose down -v' | Out-Null
    if (Test-Path $logDir) { Remove-Item -Recurse -Force $logDir }
    Write-Host '  done. Run .\deploy\dev.ps1 up to start fresh (the seed recreates your admin; set up TOTP again).'
}

switch ($Command) {
    'up' { Invoke-Up }
    'down' { Invoke-Down }
    'status' { Invoke-Status }
    'reset' { Invoke-Reset }
    'init' { Initialize-EnvFiles }
}

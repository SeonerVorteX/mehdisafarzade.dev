function Get-Processes {
    if (-not (Test-Path $pidFile)) { return @() }
    $raw = Get-Content $pidFile -Raw
    if (-not $raw -or -not $raw.Trim()) { return @() }
    return @(@($raw | ConvertFrom-Json) | Where-Object { $null -ne $_ -and $_.PSObject.Properties['pid'] })
}

function Test-Alive([int]$ProcessId) {
    return $null -ne (Get-Process -Id $ProcessId -ErrorAction SilentlyContinue)
}

function Stop-Tree([int]$ProcessId) {
    if (-not (Test-Alive $ProcessId)) { return }
    if ($env:OS -eq 'Windows_NT') {
        & taskkill.exe /PID $ProcessId /T /F 2>&1 | Out-Null
    } else {
        Stop-Process -Id $ProcessId -Force -ErrorAction SilentlyContinue
    }
}

function Start-Background([string]$Name, [string]$Dir, [string[]]$Arguments) {
    $out = Join-Path $logDir "$Name.log"
    $err = Join-Path $logDir "$Name.err.log"
    $node = (Get-Command node).Source
    $p = Start-Process -FilePath $node -ArgumentList $Arguments -WorkingDirectory $Dir -PassThru `
        -WindowStyle Hidden -RedirectStandardOutput $out -RedirectStandardError $err
    return [pscustomobject]@{ name = $Name; pid = $p.Id; log = $out }
}

function Get-HttpStatus([string]$Url) {
    try {
        if ($PSVersionTable.PSVersion.Major -ge 6) {
            $r = Invoke-WebRequest -Uri $Url -Method Get -TimeoutSec 3 -SkipCertificateCheck -MaximumRedirection 0 -SkipHttpErrorCheck -ErrorAction Stop
            return [int]$r.StatusCode
        }
        # Windows PowerShell 5.1: curl.exe ships with Windows 10+ and handles the self-signed gate cert.
        $code = & curl.exe -sk -o NUL -w '%{http_code}' --max-time 3 $Url 2>$null
        return [int]$code
    } catch {
        return 0
    }
}

function Wait-Http([string]$Name, [string]$Url, [int[]]$Ok, [int]$TimeoutSec, [string]$Log) {
    $deadline = (Get-Date).AddSeconds($TimeoutSec)
    while ((Get-Date) -lt $deadline) {
        $code = Get-HttpStatus $Url
        if ($Ok -contains $code) { Write-Host "  ready    $Name  $Url ($code)"; return }
        Start-Sleep -Seconds 2
    }
    Write-Host "  NOT READY $Name ($Url). Last lines of $Log :" -ForegroundColor Yellow
    if ($Log -and (Test-Path $Log)) { Get-Content $Log -Tail 20 | ForEach-Object { Write-Host "    $_" } }
    $errLog = $Log -replace '\.log$', '.err.log'
    if ($Log -and (Test-Path $errLog)) { Get-Content $errLog -Tail 20 | ForEach-Object { Write-Host "    $_" } }
    throw "$Name did not become ready within $TimeoutSec s."
}

function Get-BusyPorts([int[]]$Ports) {
    $busy = @()
    foreach ($port in $Ports) {
        $c = New-Object System.Net.Sockets.TcpClient
        try {
            $ar = $c.BeginConnect('127.0.0.1', $port, $null, $null)
            if ($ar.AsyncWaitHandle.WaitOne(300) -and $c.Connected) { $busy += $port }
        } catch { } finally { $c.Close() }
    }
    return $busy
}

function Assert-Tools {
    foreach ($t in @('docker', 'node', 'git')) {
        if (-not (Get-Command $t -ErrorAction SilentlyContinue)) { throw "'$t' is not on PATH." }
    }
    $prev = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    & docker info 2>&1 | Out-Null
    $dockerOk = ($LASTEXITCODE -eq 0)
    $ErrorActionPreference = $prev
    if (-not $dockerOk) { throw 'Docker is not running. Start Docker Desktop and try again.' }
    $major = [int]((& node -v).TrimStart('v').Split('.')[0])
    if ($major -lt 22) { throw "Node 22+ is required (found $(& node -v))." }
}


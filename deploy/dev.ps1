function Write-Step([string]$Text) { Write-Host "`n> $Text" -ForegroundColor Cyan }

function Invoke-Quiet([string]$Dir, [string]$Exe, [string[]]$Arguments, [string]$What) {
    # Native tools print progress on stderr; PS 5.1 would treat that as an error under Stop.
    $prev = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    Push-Location $Dir
    try { $out = & $Exe @Arguments 2>&1 | ForEach-Object { "$_" }; $code = $LASTEXITCODE }
    finally { Pop-Location; $ErrorActionPreference = $prev }
    if ($code -ne 0) {
        Write-Host ($out | Select-Object -Last 25 | Out-String)
        throw "$What failed (exit $code)."
    }
    return $out
}

function Invoke-Yarn([string]$Dir, [string[]]$Arguments, [string]$What) {
    Invoke-Quiet $Dir 'node' (@($yarn) + $Arguments) $What | Out-Null
}

function New-Secret([int]$Bytes) {
    $b = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($b) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($b)
}

function New-Passphrase {
    $words = 'amber cobalt delta ember fjord granite harbor island juniper kestrel lumen meadow nimbus orchid prairie quartz'.Split(' ')
    $b = New-Object byte[] 5
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    return (($b[0..3] | ForEach-Object { $words[$_ % $words.Count] }) -join '-') + '-' + (100 + ($b[4] % 900))
}

function Write-NewFile([string]$Path, [string]$Content) {
    if (Test-Path $Path) { Write-Host "  kept     $($Path.Substring($repo.Length + 1)) (exists, not touched)"; return $false }
    # UTF-8 without BOM, LF endings (dotenv and Next read it fine either way).
    [IO.File]::WriteAllText($Path, ($Content -replace "`r", ''), (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "  created  $($Path.Substring($repo.Length + 1))"
    return $true
}


<#
.SYNOPSIS
    One-command local development for mehdisafarzade.dev. See LOCAL_DEV.md.

.DESCRIPTION
    up      Create missing env files (dev-only secrets; existing files are never
            touched), install dependencies if needed, start the portfolio-* dev
            containers, run migrations + the idempotent seed, start the local device
            gate, then the API (:3100) and both Next apps (web :5600, admin :5603).
            On first run it also enrolls this browser in the local gate.
    down    Stop the API, the Next apps, the local gate and the dev containers (data kept).
    status  What's running and on which ports.
    reset   Wipe local data (database, Redis, RabbitMQ, S3, logs) after confirmation.
            Env files and enrolled gate devices are kept.
    init    Only create missing env files (what 'up' does first).

.EXAMPLE
    .\deploy\dev.ps1 up
    .\deploy\dev.ps1 status
    .\deploy\dev.ps1 down
    .\deploy\dev.ps1 reset
#>
[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [ValidateSet('up', 'down', 'status', 'reset', 'init')]
    [string]$Command = 'up',

    # Device name to enroll in the local gate on first run.
    [string]$Device = 'pc',

    # Admin email written into a NEW api/.env.dev (default: git user.email).
    [string]$AdminEmail,

    # Don't open the browser / don't enroll automatically.
    [switch]$NoBrowser,

    # reset: skip the confirmation prompt.
    [switch]$Yes
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$api = Join-Path $repo 'api'
$fe = Join-Path $repo 'frontend'
$gate = Join-Path (Join-Path $PSScriptRoot 'device-gate') 'gate.ps1'
$stateDir = Join-Path $PSScriptRoot '.dev'
$logDir = Join-Path $stateDir 'logs'
$pidFile = Join-Path $stateDir 'processes.json'
$composeFile = Join-Path $api 'docker-compose.dev.yml'
$yarn = '.yarn/releases/yarn-4.12.0.cjs'
$services = @('db-dev', 'redis-dev', 'rabbitmq-dev', 's3-dev', 'mailpit-dev')

